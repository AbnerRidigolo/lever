import { readFileSync } from 'node:fs';

import { describe, expect, it } from 'vitest';

import { findProductById, findProductBySlug, listProducts } from '@/catalog/catalog';
import { generateCatalog, slugify } from '@/catalog/generate';
import { catalogSchema } from '@/catalog/schema';

const versioned: unknown = JSON.parse(
  readFileSync(new URL('../src/catalog/products.json', import.meta.url), 'utf8'),
);

describe('fictitious catalog generated by a seed', () => {
  it('AC-8.1: the versioned catalog matches the schema with unique ids and slugs', () => {
    const products = catalogSchema.parse(versioned);
    expect(products).toHaveLength(24);
    expect(new Set(products.map((p) => p.category)).size).toBe(4);
  });

  it('AC-8.1: regenerating with the same seed gives the versioned file', () => {
    expect(generateCatalog()).toEqual(versioned);
  });

  it('a different seed gives a different catalog', () => {
    expect(generateCatalog(1)).not.toEqual(generateCatalog());
  });

  it('rejects duplicate slugs and ids', () => {
    const [first] = generateCatalog();
    expect(catalogSchema.safeParse([first, first]).success).toBe(false);
  });

  it('finds products by id, slug and category', () => {
    const [first] = listProducts();
    if (first === undefined) throw new Error('empty catalog');
    expect(findProductById(first.id)).toBe(first);
    expect(findProductBySlug(first.slug)).toBe(first);
    expect(listProducts('lazer')).toHaveLength(6);
    expect(listProducts('lazer').every((p) => p.category === 'lazer')).toBe(true);
    expect(findProductBySlug('does-not-exist')).toBeUndefined();
  });

  it('slugifies accented names', () => {
    expect(slugify('Luminária Maré')).toBe('luminaria-mare');
    expect(slugify('Porta-lápis Ipê')).toBe('porta-lapis-ipe');
  });
});
